CREATE INDEX idx_sys_role_menu_menu ON sys_role_menu (menu_id);

-- 项目
CREATE TABLE project (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  project_code VARCHAR(32) NOT NULL,
  project_name VARCHAR(128) NOT NULL,
  project_type VARCHAR(64) NOT NULL,
  investment_amount DECIMAL(18,2) NOT NULL,
  dept_id BIGINT,
  plan_start_date DATE,
  plan_end_date DATE,
  valid_until DATE,
  description VARCHAR(512),
  status VARCHAR(32) NOT NULL,
  source VARCHAR(32) DEFAULT 'MANUAL',
  issue_time DATETIME,
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_project PRIMARY KEY (id),
  CONSTRAINT uk_project_code UNIQUE (project_code)
);
CREATE INDEX idx_project_type ON project (project_type);
CREATE INDEX idx_project_dept ON project (dept_id);
CREATE INDEX idx_project_status_time ON project (status, create_time);

