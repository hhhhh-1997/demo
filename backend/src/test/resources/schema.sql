-- H2 兼容 DDL（供集成测试；与主 schema 同表结构，AUTO_INCREMENT → IDENTITY，内联 KEY → CREATE INDEX）
-- 字典类型
CREATE TABLE sys_dict_type (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  dict_name VARCHAR(128) NOT NULL,
  dict_type VARCHAR(64) NOT NULL,
  status TINYINT DEFAULT 1,
  remark VARCHAR(256),
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_sys_dict_type PRIMARY KEY (id),
  CONSTRAINT uk_sys_dict_type UNIQUE (dict_type)
);

-- 字典数据
CREATE TABLE sys_dict_data (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  dict_type VARCHAR(64) NOT NULL,
  dict_label VARCHAR(128) NOT NULL,
  dict_value VARCHAR(128) NOT NULL,
  sort INT DEFAULT 0,
  status TINYINT DEFAULT 1,
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_sys_dict_data PRIMARY KEY (id),
  CONSTRAINT uk_sys_dict_data UNIQUE (dict_type, dict_value)
);

-- 部门
CREATE TABLE sys_dept (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  dept_name VARCHAR(64) NOT NULL,
  parent_id BIGINT DEFAULT 0,
  sort INT DEFAULT 0,
  status TINYINT DEFAULT 1,
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_sys_dept PRIMARY KEY (id)
);
CREATE INDEX idx_sys_dept_parent ON sys_dept (parent_id);

-- 用户
CREATE TABLE sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  username VARCHAR(64) NOT NULL,
  password VARCHAR(128) NOT NULL,
  nickname VARCHAR(64),
  dept_id BIGINT,
  status TINYINT DEFAULT 1,
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_sys_user PRIMARY KEY (id),
  CONSTRAINT uk_sys_user_username UNIQUE (username)
);
CREATE INDEX idx_sys_user_dept ON sys_user (dept_id);

-- 角色
CREATE TABLE sys_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  role_name VARCHAR(64) NOT NULL,
  role_key VARCHAR(64) NOT NULL,
  sort INT DEFAULT 0,
  status TINYINT DEFAULT 1,
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_sys_role PRIMARY KEY (id),
  CONSTRAINT uk_sys_role_key UNIQUE (role_key)
);

-- 菜单（M=目录 C=菜单 F=按钮）
CREATE TABLE sys_menu (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  menu_name VARCHAR(64) NOT NULL,
  parent_id BIGINT DEFAULT 0,
  path VARCHAR(200),
  component VARCHAR(200),
  perms VARCHAR(100),
  menu_type CHAR(1) NOT NULL,
  icon VARCHAR(64),
  sort INT DEFAULT 0,
  visible TINYINT DEFAULT 1,
  status TINYINT DEFAULT 1,
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_sys_menu PRIMARY KEY (id)
);
CREATE INDEX idx_sys_menu_parent ON sys_menu (parent_id);

-- 用户-角色 / 角色-菜单
CREATE TABLE sys_user_role (
