CREATE INDEX idx_project_audit_project ON project_audit (project_id);

-- 自动化测试-场景
CREATE TABLE at_scenario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  name VARCHAR(100) NOT NULL,
  description VARCHAR(500),
  base_url VARCHAR(255),
  variables CLOB,
  create_by BIGINT,
  create_time DATETIME,
  update_by BIGINT,
  update_time DATETIME,
  CONSTRAINT pk_at_scenario PRIMARY KEY (id)
);

-- 自动化测试-步骤
CREATE TABLE at_step (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  scenario_id BIGINT NOT NULL,
  step_order INT NOT NULL,
  name VARCHAR(100),
  params CLOB NOT NULL,
  create_time DATETIME,
  update_time DATETIME,
  CONSTRAINT pk_at_step PRIMARY KEY (id)
);
CREATE INDEX idx_at_step_scenario ON at_step (scenario_id);

-- 自动化测试-执行记录
CREATE TABLE at_run (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  scenario_id BIGINT,
  status TINYINT,
  fail_step_id BIGINT,
  error_msg VARCHAR(1000),
  start_time DATETIME,
  end_time DATETIME,
  trigger_by BIGINT,
  create_time DATETIME,
  CONSTRAINT pk_at_run PRIMARY KEY (id)
);
CREATE INDEX idx_at_run_scenario ON at_run (scenario_id);

-- 自动化测试-步骤结果
CREATE TABLE at_step_result (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  run_id BIGINT NOT NULL,
  step_id BIGINT,
  step_order INT,
  name VARCHAR(100),
  status TINYINT,
  request_snapshot CLOB,
  response_snapshot CLOB,
  assert_detail CLOB,
  error_msg VARCHAR(1000),
  start_time DATETIME,
  end_time DATETIME,
  CONSTRAINT pk_at_step_result PRIMARY KEY (id)
);
CREATE INDEX idx_at_step_result_run ON at_step_result (run_id);
